// Copies the woff2 files Midaad needs from @fontsource packages into public/fonts
// and writes src/shared/fonts.generated.ts describing each @font-face.
// Fonts are bundled so the extension never calls a font CDN.
import { readFileSync, writeFileSync, mkdirSync, copyFileSync } from 'node:fs';
import { join } from 'node:path';

const FONTS = [
  { id: 'literata', pkg: '@fontsource-variable/literata', slug: 'literata', css: ['wght.css', 'wght-italic.css'], subsets: ['latin', 'latin-ext'] },
  { id: 'source-sans', pkg: '@fontsource-variable/source-sans-3', slug: 'source-sans-3', css: ['wght.css', 'wght-italic.css'], subsets: ['latin', 'latin-ext'] },
  { id: 'atkinson', pkg: '@fontsource/atkinson-hyperlegible', slug: 'atkinson-hyperlegible', css: ['400.css', '700.css', '400-italic.css', '700-italic.css'], subsets: ['latin', 'latin-ext'] },
  { id: 'opendyslexic', pkg: '@fontsource/opendyslexic', slug: 'opendyslexic', css: ['400.css', '700.css', '400-italic.css', '700-italic.css'], subsets: ['latin'] },
  { id: 'noto-naskh', pkg: '@fontsource-variable/noto-naskh-arabic', slug: 'noto-naskh-arabic', css: ['wght.css'], subsets: ['arabic'] },
  { id: 'amiri', pkg: '@fontsource/amiri', slug: 'amiri', css: ['400.css', '700.css'], subsets: ['arabic'] },
];

const outDir = 'public/fonts';
mkdirSync(outDir, { recursive: true });
const faces = [];

for (const font of FONTS) {
  const nameRe = new RegExp(`^${font.slug}-(.+)-(wght|[0-9]{3})-(normal|italic)$`);
  for (const cssFile of font.css) {
    const css = readFileSync(join('node_modules', font.pkg, cssFile), 'utf8');
    for (const [, name, body] of css.matchAll(/\/\*\s*([\w-]+)\s*\*\/\s*@font-face\s*\{([^}]*)\}/g)) {
      const m = nameRe.exec(name);
      if (!m || !font.subsets.includes(m[1])) continue;
      const prop = (p) => new RegExp(`${p}:\s*([^;]+);`).exec(body)?.[1].trim();
      const file = /url\(\.\/files\/([^)]+\.woff2)\)/.exec(body)?.[1];
      if (!file) continue;
      copyFileSync(join('node_modules', font.pkg, 'files', file), join(outDir, file));
      faces.push({ font: font.id, file, weight: prop('font-weight'), style: prop('font-style'), unicodeRange: prop('unicode-range') });
    }
  }
}

const ts = `// Generated by scripts/copy-fonts.mjs. Do not edit by hand.
export interface FontFaceSpec { font: string; file: string; weight: string; style: string; unicodeRange?: string }
export const FONT_FACES: readonly FontFaceSpec[] = ${JSON.stringify(faces, null, 2)};
`;
writeFileSync('src/shared/fonts.generated.ts', ts);
console.log(`copied ${faces.length} font faces`);
